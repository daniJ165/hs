reset=$(tput sgr0)

# Initialize the 'current' color variable
current_color=$orange

while true; do
    clear
    
    # Print the message with the current color
    echo "${current_color}${message}${reset}"

    # Swap the color for the next loop
    if [ "$current_color" = "$orange" ]; then
        current_color=$green
    else
        current_color=$orange
    fi

    sleep 1
done


done


